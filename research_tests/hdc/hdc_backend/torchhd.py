"""TorchHD backend adapter for the Zog Zoo component benchmark harness.

This adapter uses the native TorchHD VSA subclasses, not dtype-inferred generic
Tensor arithmetic. In particular BSC must remain Boolean for XOR binding.

The adapter is CPU-only by design; the project is targeting CPU/FPGA/ASIC HDC.
Historical result files generated by older adapters must not be overwritten.
"""
from __future__ import annotations

import numpy as np
import torch
import torchhd as hd

from . import HDCBackend


class TorchHDBackend(HDCBackend):
    name = "torchhd"

    def __init__(self, D: int, vsa: str = "FHRR", seed: int = 0):
        self.D = int(D)
        self.vsa = vsa.upper()
        self.seed = int(seed)
        if self.vsa not in ("BSC", "MAP", "HRR", "FHRR"):
            raise ValueError(f"Unsupported TorchHD VSA: {self.vsa!r}")

    @property
    def dtype(self) -> np.dtype:
        return np.dtype({"BSC": np.bool_, "MAP": np.float32,
                         "HRR": np.float32, "FHRR": np.complex64}[self.vsa])

    @staticmethod
    def _to_np(t) -> np.ndarray:
        if isinstance(t, torch.Tensor):
            return t.detach().cpu().numpy()
        return np.asarray(t)

    def _to_th(self, arr: np.ndarray):
        arr = np.asarray(arr)
        if self.vsa == "BSC":
            # Accept native bits (False/True or 0/1), or explicit bipolar signs.
            # Under this mapping 0/False == +1 and 1/True == -1.
            if arr.dtype == np.bool_:
                bits = arr
            elif np.all((arr == 0) | (arr == 1)):
                bits = arr.astype(np.bool_)
            elif np.all((arr == -1) | (arr == 1)):
                bits = arr < 0
            else:
                raise ValueError("BSC operands must be Boolean, 0/1, or bipolar ±1")
            return hd.ensure_vsa_tensor(torch.from_numpy(np.ascontiguousarray(bits)), vsa="BSC")
        if self.vsa == "FHRR":
            t = torch.from_numpy(np.ascontiguousarray(arr.astype(np.complex64, copy=False)))
        else:
            t = torch.from_numpy(np.ascontiguousarray(arr.astype(np.float32, copy=False)))
        return hd.ensure_vsa_tensor(t, vsa=self.vsa)

    def generate(self, n: int, D: int | None = None, seed: int | None = None) -> np.ndarray:
        dim = int(D if D is not None else self.D)
        generator = torch.Generator(device="cpu").manual_seed(self.seed if seed is None else int(seed))
        return self._to_np(hd.random(int(n), dim, vsa=self.vsa, generator=generator, device="cpu")).copy()

    def bind(self, a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return self._to_np(hd.bind(self._to_th(a), self._to_th(b)))

    def unbind(self, a: np.ndarray, bound: np.ndarray) -> np.ndarray:
        return self._to_np(hd.bind(self._to_th(bound), hd.inverse(self._to_th(a))))

    def bundle(self, vectors: np.ndarray) -> np.ndarray:
        vectors = np.asarray(vectors)
        if vectors.ndim == 1:
            vectors = vectors[None, :]
        if not len(vectors):
            raise ValueError("Cannot bundle an empty collection")
        if self.vsa == "BSC":
            # Native BSC majority vote, with a reproducible tie-breaker.
            generator = torch.Generator(device="cpu").manual_seed(self.seed)
            return self._to_np(self._to_th(vectors).multibundle(generator=generator))
        # TorchHD's MAP/HRR/FHRR multibundle is additive, intentionally not the
        # same as ZogZoo's threshold/normalization semantics.
        return self._to_np(hd.multibundle(self._to_th(vectors)))

    def score(self, bank: np.ndarray, query: np.ndarray) -> np.ndarray:
        bank = np.asarray(bank)
        if bank.ndim == 1:
            bank = bank[None, :]
        return self._to_np(hd.cos(self._to_th(query), self._to_th(bank))).reshape(-1)

    def similarity(self, a: np.ndarray, b: np.ndarray) -> float:
        return float(self._to_np(hd.cos(self._to_th(a), self._to_th(b))).item())

    def perturb(self, hv: np.ndarray, kind: str, alpha: float,
                rng: np.random.Generator | None = None) -> np.ndarray:
        hv = np.asarray(hv)
        if alpha == 0.0 or kind.lower() == "clean":
            return hv.copy()
        if not 0 <= alpha <= 1:
            raise ValueError("alpha must be in [0,1]")
        if rng is None:
            rng = np.random.Generator(np.random.PCG64(self.seed))
        if self.vsa == "BSC":
            return np.logical_xor(self._to_np(self._to_th(hv)), rng.random(hv.shape) < alpha)
        if self.vsa == "MAP":
            out = hv.astype(np.float32, copy=True)
            out[rng.random(hv.shape) < alpha] *= -1
            return out
        if self.vsa == "HRR":
            return hv.astype(np.float32) + (alpha * np.std(hv)) * rng.standard_normal(hv.shape).astype(np.float32)
        # FHRR: jitter a random alpha proportion of phase components.
        out = hv.astype(np.complex64, copy=True)
        mask = rng.random(hv.shape) < alpha
        out[mask] *= np.exp(1j * rng.normal(0, alpha * np.pi / 4, mask.sum())).astype(np.complex64)
        return out
